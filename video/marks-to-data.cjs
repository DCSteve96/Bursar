// Turns a recording (the .webm Playwright wrote and its marks.json) into public/screen.mp4 and src/data.ts.
// The capture's clock strip (bottom 12 px, see record.cjs) is decoded frame by frame, so every mark, taken on the
// script's clock, lands on the frame that really shows it; the strip is cropped away by the video.
// usage: node marks-to-data.cjs <out dir of record.cjs>
const fs = require("fs"), path = require("path");
const { execFileSync } = require("child_process");
const dir = process.argv[2];
const webm = fs.readdirSync(dir).find((f) => f.endsWith(".webm"));
const marks = JSON.parse(fs.readFileSync(path.join(dir, "marks.json"), "utf8"));
const W = 1600, BAR = 12, CELLS = 16, FPS = 30, PROBE = 10;
const mp4 = path.join(__dirname, "public", "screen.mp4");
execFileSync("ffmpeg", ["-v", "error", "-y", "-i", path.join(dir, webm), "-r", String(FPS), "-c:v", "libx264", "-preset", "slow", "-crf", "17", "-pix_fmt", "yuv420p", "-movflags", "+faststart", mp4], { stdio: "inherit" });
// decode the strip at PROBE frames per second
const raw = execFileSync("ffmpeg", ["-v", "error", "-i", mp4, "-vf", `crop=${W}:${BAR}:0:ih-${BAR},fps=${PROBE}`, "-f", "rawvideo", "-pix_fmt", "gray", "-"], { maxBuffer: 1 << 30 });
const frameBytes = W * BAR, cw = W / CELLS, row = Math.floor(BAR / 2);
const clock = []; // clock[k] = script seconds shown at video second k / PROBE
for (let k = 0; k * frameBytes < raw.length; k++) {
  let v = 0;
  for (let i = 0; i < CELLS; i++) { const px = raw[k * frameBytes + row * W + Math.floor(i * cw + cw / 2)]; v = v * 2 + (px > 128 ? 1 : 0); }
  clock.push(v / 10);
}
// a frame with a damaged strip reads as a jump: keep the clock monotone and ignore outliers
let last = 0; const clean = clock.map((s) => { if (s >= last && s < last + 5) last = s; return last; });
const videoAt = (s) => { const k = clean.findIndex((c) => c >= s); return (k < 0 ? clean.length - 1 : k) / PROBE; };
const drift = marks.segments.map((g) => (videoAt(g.start) - g.start).toFixed(1));
console.log(`capture ${(clock.length / PROBE).toFixed(1)} s, clock ${clean[0]} .. ${clean[clean.length - 1]} s, video ahead of the script by ${drift.join(", ")} s at the segment starts`);
// segments: clips in video time, skips cut out; captions and zooms at play seconds inside their segment
const segments = marks.segments.map((g) => {
  const cuts = marks.skips.filter((k) => k.from > g.start && k.to < g.end).sort((a, b) => a.from - b.from);
  const bounds = [g.start]; for (const k of cuts) bounds.push(k.from, k.to); bounds.push(g.end);
  const clips = []; for (let i = 0; i < bounds.length; i += 2) clips.push({ from: +videoAt(bounds[i]).toFixed(2), to: +videoAt(bounds[i + 1]).toFixed(2) });
  const play = (s) => { // play seconds of a script time inside this segment
    const v = videoAt(s); let acc = 0;
    for (const c of clips) { if (v <= c.to) return +(acc + Math.max(0, v - c.from)).toFixed(2); acc += c.to - c.from; }
    return +acc.toFixed(2);
  };
  const inSeg = (m) => m.t >= g.start && m.t <= g.end;
  return {
    seconds: +clips.reduce((a, c) => a + c.to - c.from, 0).toFixed(2),
    clips,
    captions: marks.captions.filter(inSeg).map((c) => ({ at: play(c.t), text: c.text })),
    zooms: marks.zooms.filter(inSeg).map((z) => ({ at: play(z.t), ms: z.ms, scale: z.scale, x: Math.round(z.x), y: Math.round(z.y), w: Math.round(z.w), h: Math.round(z.h) })),
  };
});
const out = `// generated by marks-to-data.cjs from the capture's marks: do not edit by hand\nexport const data = ${JSON.stringify({ segments }, null, 1)} as const;\n`;
fs.writeFileSync(path.join(__dirname, "src", "data.ts"), out);
console.log("segments:", segments.map((s) => `${s.seconds}s (${s.clips.length} clips, ${s.captions.length} captions)`).join("; "));
